/*
 * tools/build_simbrief_models.mjs
 *
 * Deterministic, offline build-time generator for the all-models 5-year and
 * 10-year Total economic TCO table in docs/simulation-results-brief.md (the
 * brief that is embedded via the SIMBRIEF marker and Blob-downloaded offline
 * from the page). FEAT-004.
 *
 * WHY THIS EXISTS
 * ---------------
 * The downloadable analysis brief must carry, for EACH of the 12 catalogue
 * models, BOTH the 5-year AND the 10-year Total economic TCO, side by side,
 * under ONE held-constant scenario so the comparison is apples-to-apples. The
 * figures are NOT invented: they are produced by the FROZEN engine
 * (src/engine.js -> computeFleet). The engine already exposes a per-plan,
 * per-year cumulative economic-TCO series,
 *
 *     computeFleet(inputs).annualSeries[plan].cumulative[0..10]
 *
 * which is the exact source of the TCO line chart in the UI. For the EV plan
 * (plan_a) of a scenario whose EV-action trucks are bound to a given model:
 *
 *     cumulative[5]  = the genuine year-5 cumulative economic TCO
 *     cumulative[10] = the full-horizon (120-month) Total economic TCO
 *
 * No engine formula change and no additive engine field are needed.
 *
 * THE HELD-CONSTANT SCENARIO (apples-to-apples base)
 * --------------------------------------------------
 * The generator reuses the shipped 'best' illustrative preset from
 * tools/fixtures/prospect_seeds.json as the single fixed base and holds it
 * IDENTICAL across all 12 models: same fleet size and composition, same duty
 * (work km/day, days/year), same energy prices (diesel + depot electricity),
 * and the same depot charging site build-up. The ONLY thing that changes
 * between the 12 runs is which catalogue model is bound as the EV on the EV
 * plan (Plan A / slot O) across the EV-action trucks - AND the EV quote (col D)
 * is held at the preset's fixed value too, so the comparison isolates the
 * per-model economics (energy use, catalogue, terminal value) rather than
 * mixing in a different quote per model. Every other input is untouched.
 *
 * It extracts cumulative[5] (5-yr) and cumulative[10] (10-yr) for plan_a and
 * writes a 12-model table into docs/simulation-results-brief.md, rewriting the
 * region BETWEEN the marker comments
 *
 *     <!-- SIMBRIEF-MODELS:BEGIN ... --> ... <!-- SIMBRIEF-MODELS:END -->
 *
 * in place on every run, so the table is always a fresh, deterministic
 * re-derivation of the frozen engine and the drift-guard harness
 * (tools/check_simbrief.mjs) can re-verify it against a fresh engine run.
 *
 * If a model yields n.a. for the scenario (a gating input unmet for that
 * model), it is shown honestly as n.a. - NEVER a substituted zero.
 *
 *   node tools/build_simbrief_models.mjs
 *
 * After running, re-embed the brief into index.html:
 *   node tools/build_index.js
 *
 * No third-party dependencies, no network, no randomness.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { computeFleet } from '../src/engine.js';

const here = dirname(fileURLToPath(import.meta.url));
const seedsPath = resolve(here, 'fixtures/prospect_seeds.json');
const briefPath = resolve(here, '../docs/simulation-results-brief.md');

/* The 12 catalogue models, in catalogue order. This list is asserted against
 * the preset's products catalogue below, so it cannot silently drift. */
export const CATALOGUE_MODELS = [
  'Farizon F3E',
  'SRM T3EV',
  'ChengLong L2EV',
  'Farizon H5E',
  'SRM T3EV+',
  'Farizon H9E 14ft',
  'Farizon H9E 20ft',
  'BYD T35 Electric Light-Duty',
  'Foton eMiler',
  'Forland S1 EV',
  'JAC N40EV',
  'Qingling EQ2',
];

export const BEGIN_MARK = '<!-- SIMBRIEF-MODELS:BEGIN  generated by tools/build_simbrief_models.mjs  DO NOT EDIT BY HAND -->';
export const END_MARK = '<!-- SIMBRIEF-MODELS:END -->';

function isNum(v) { return typeof v === 'number' && isFinite(v); }
function clone(x) { return JSON.parse(JSON.stringify(x)); }
function money(v) { return isNum(v) ? 'S$' + Math.round(v).toLocaleString('en-US') : 'n.a.'; }

/* Build the held-constant EV-plan state with `model` bound as the EV on every
 * EV-action Plan A truck (slot O === 'EV'). Everything else (fleet, duty,
 * energy, site, EV quote col D) is left exactly as the 'best' preset authored
 * it, so the scenario is identical across all 12 models. This mirrors the
 * engine's Plan A (slot O) projection: the engine reads col B as the bound
 * model for that truck's EV path. */
export function buildModelState(baseInputs, model) {
  const s = clone(baseInputs);
  for (const rp of s.replacement_plan.rows) {
    if (!rp || rp.A == null) continue;
    if (rp.O === 'EV') rp.B = model;
  }
  return s;
}

/* Run the frozen engine for one model and extract the EV plan's year-5 and
 * year-10 cumulative economic TCO. Returns { y5, y10 } (numbers or null). */
export function modelTco(baseInputs, model) {
  const out = computeFleet(buildModelState(baseInputs, model));
  const cum = out.annualSeries && out.annualSeries.plan_a && out.annualSeries.plan_a.cumulative;
  const c5 = cum ? cum[5] : null;
  const c10 = cum ? cum[10] : null;
  return { y5: isNum(c5) ? c5 : null, y10: isNum(c10) ? c10 : null };
}

/* Compute the full 12-model result set against the 'best' held-constant base. */
export function computeModelTable(seeds) {
  const base = seeds.cases.find((c) => c.id === 'best');
  if (!base) throw new Error('prospect_seeds.json has no "best" case to use as the held-constant base');
  // Guard: the 12-model list must match the preset's product catalogue exactly.
  const cat = (base.inputs.products.rows || []).map((r) => r.A);
  for (const m of CATALOGUE_MODELS) {
    if (cat.indexOf(m) === -1) throw new Error('catalogue model missing from preset products: ' + m);
  }
  const rows = CATALOGUE_MODELS.map((model) => {
    const { y5, y10 } = modelTco(base.inputs, model);
    return { model, y5, y10 };
  });
  return rows;
}

/* Render the markdown section (header + table + caveats) between the markers.
 * SRM T3EV+ is flagged as the primary recommended model. */
export function renderSection(rows) {
  let md = '';
  md += BEGIN_MARK + '\n';
  md += '## 6. 5-year and 10-year Total economic TCO by portfolio model\n\n';
  md += 'This table reports, for **every one of the 12 portfolio models**, both the\n';
  md += '**5-year** and the **10-year** Total economic TCO, computed by the frozen engine\n';
  md += '(`src/engine.js`, `computeFleet`) under ONE held-constant scenario so the\n';
  md += 'per-model comparison is apples-to-apples.\n\n';
  md += '**Held-constant scenario.** The shipped **Best** illustrative preset is used as the\n';
  md += 'single fixed base and is held identical across all 12 models: the same fleet size\n';
  md += 'and composition (4 EV-action trucks within a 100-truck register), the same duty\n';
  md += '(work km/day and days/year), the same energy prices (commercial diesel and depot\n';
  md += 'electricity), the same depot charging-site build-up, and the same EV purchase quote\n';
  md += '(col D). The **only** input that changes between rows is which catalogue model is\n';
  md += 'bound as the EV on the EV plan (Plan A). Holding the quote constant isolates each\n';
  md += "model's own economics - its energy use (kWh/km), catalogue base and year-10 asset\n";
  md += 'value - rather than mixing in a different quote per model.\n\n';
  md += '**How the figures are derived.** The engine exposes a per-plan, per-year cumulative\n';
  md += 'economic-TCO series (`annualSeries[plan].cumulative[0..10]`) - the same series that\n';
  md += 'draws the TCO line chart. For the EV plan of each run: **5-yr = `cumulative[5]`**\n';
  md += '(the cumulative economic cost at year 5) and **10-yr = `cumulative[10]`** (the\n';
  md += 'full-horizon 120-month Total economic TCO). No figure is invented and no engine\n';
  md += 'formula was changed; these are genuine frozen-engine cumulative points. Where a\n';
  md += 'model gates out for the scenario the cell shows **n.a.**, never a substituted zero.\n\n';
  md += '| Portfolio model | 5-year Total economic TCO | 10-year Total economic TCO |\n';
  md += '|---|---:|---:|\n';
  for (const r of rows) {
    const name = r.model === 'SRM T3EV+' ? '**SRM T3EV+** (primary)' : r.model;
    md += '| ' + name + ' | ' + money(r.y5) + ' | ' + money(r.y10) + ' |\n';
  }
  md += '\n';
  md += '**Caveats (unchanged honesty signals).** These figures are a **diagnostic, not a\n';
  md += 'quotation**. The **SRM is the primary recommendation** (SRM T3EV+ on Plan A);\n';
  md += 'competitor models are shown on the same held-constant duty for a like-for-like\n';
  md += 'comparison. Catalogue **body-fit / payload status is Unconfirmed** for every model,\n';
  md += 'so no row reads as a clean "best fit" until that status is confirmed with a real\n';
  md += 'quote. All preset figures are **illustrative** (the Best preset is an\n';
  md += 'engine-verified demonstration, not a real customer). Regenerate this table\n';
  md += 'deterministically with `node tools/build_simbrief_models.mjs` and re-embed it with\n';
  md += '`node tools/build_index.js`.\n';
  md += END_MARK + '\n';
  return md;
}

/* Rewrite the marked region of the brief in place. */
export function rewriteBrief(briefText, sectionMd) {
  const b = briefText.indexOf(BEGIN_MARK);
  const e = briefText.indexOf(END_MARK);
  if (b === -1 || e === -1) {
    throw new Error('SIMBRIEF-MODELS markers not found in docs/simulation-results-brief.md');
  }
  const endFull = e + END_MARK.length;
  return briefText.slice(0, b) + sectionMd.replace(/\n$/, '') + briefText.slice(endFull);
}

// -------- Run when invoked directly (not when imported by the harness) -------
const invokedDirectly = resolve(process.argv[1] || '') === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const seeds = JSON.parse(readFileSync(seedsPath, 'utf8'));
  const rows = computeModelTable(seeds);
  const section = renderSection(rows);
  const brief = readFileSync(briefPath, 'utf8');
  const next = rewriteBrief(brief, section);
  writeFileSync(briefPath, next, 'utf8');

  console.log('Regenerated the 12-model 5yr/10yr Total economic TCO table in');
  console.log('docs/simulation-results-brief.md (held-constant = "best" preset).\n');
  console.log('Model'.padEnd(30) + '5-year'.padStart(16) + '10-year'.padStart(16));
  for (const r of rows) {
    console.log(r.model.padEnd(30) + money(r.y5).padStart(16) + money(r.y10).padStart(16));
  }
  console.log('\nNow run: node tools/build_index.js  (re-embeds the brief into index.html)');
}
